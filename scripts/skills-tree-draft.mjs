  RxJS: "Frontend",
  Redux: "Frontend",
  "SPA frameworks": "Frontend",
  Angular: "SPA frameworks",
  AngularJS: "SPA frameworks",
  React: "SPA frameworks",
  "Next.js": "SPA frameworks",
  Hooks: "React",
  Patterns: "React",
  Context: "Patterns",
  Provider: "Patterns",
  "Styling & animation": "Frontend",
  GSAP: "Styling & animation",
  "Framer Motion": "Styling & animation",
  "Build tools": "Frontend",
  Webpack: "Build tools",
  Gulp: "Build tools",

  Backend: null,
  "C#": "Backend",
  ".NET": "Backend",
  Java: "Backend",
  "Spring Boot": "Backend",
  "Node.js": "Backend",
  PHP: "Backend",
  CakePHP: "Backend",
  "REST APIs": "Backend",
  OAuth: "Backend",
  WinForms: "Backend",

  "CMS & e-commerce": null,
  WordPress: "CMS & e-commerce",
  Drupal: "CMS & e-commerce",
  ShopSite: "CMS & e-commerce",
  "E-commerce": "CMS & e-commerce",

  "Data & Messaging": null,
  PostgreSQL: "Data & Messaging",
