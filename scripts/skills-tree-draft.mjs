  "Cloud & DevOps": null,
  AWS: "Cloud & DevOps",
  EC2: "AWS",
  RDS: "AWS",
  S3: "AWS",
  Azure: "Cloud & DevOps",
  "Azure Container Apps": "Azure",
  Docker: "Cloud & DevOps",
  "CI/CD": "Cloud & DevOps",
