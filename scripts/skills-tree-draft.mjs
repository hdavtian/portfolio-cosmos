// Rebuilds docs/skills-tree-draft.md from the dry run, so the list Harma marks
// up is complete by construction: every technology the migration would create
// appears exactly once, either filed under a parent, merged away, or kept as
// prose. Anything not accounted for is listed as UNFILED rather than dropped.
//
//   node scripts/skills-tree-draft.mjs
//
// Writes one file and touches no database.
import { readFileSync, writeFileSync } from "node:fs";
import { MERGES, PROSE, RETIRED, TREE } from "./lib/skills-plan.mjs";

const proposal = JSON.parse(readFileSync("db-backups/skills-migration-proposal.json", "utf8"));

const existing = new Set(proposal.technologies.filter((t) => t.sources.includes("tree") || t.sources.includes("skill")).map((t) => t.name));
const proposed = new Set(proposal.technologies.map((t) => t.name));
const merged = new Set(Object.keys(MERGES));
const prose = new Set(PROSE);

// Everything the migration would create must be accounted for exactly once.
const unfiled = [...proposed].filter((n) => !(n in TREE) && !merged.has(n) && !prose.has(n) && !(n in RETIRED));
// And nothing in the tree should be a name the data never produced, except the
// roots and groups invented here.
const invented = Object.keys(TREE).filter((n) => !proposed.has(n));

const childrenOf = (parent) => Object.entries(TREE).filter(([, p]) => p === parent).map(([n]) => n);
const isNew = (name) => !existing.has(name);
const roots = Object.entries(TREE).filter(([, p]) => p === null).map(([n]) => n);

const L = [];
L.push("# The tree: a draft to correct");
L.push("");
L.push(`Generated by \`scripts/skills-tree-draft.mjs\` on ${new Date().toISOString().slice(0, 10)} from the dry run.`);
L.push("Nothing here is built.");
L.push("");
L.push("## What I need from you");
L.push("");
L.push("**I have already proposed a parent for every technology.** You are not");
L.push("filling in blanks - you are correcting mine. So:");
L.push("");
L.push("1. Read section 2 and tell me the rows where the parent is wrong.");
L.push("2. Answer the questions in section 4.");
L.push("3. Skim sections 5 and 6 and tell me anything that should not be there.");
L.push("");
L.push("Marking up is easiest as a list: `HTML Email -> Marketing & analytics`.");
L.push("Say nothing about a row and I take it as agreed.");
L.push("");
L.push("**NEW** in the table means the record does not exist today. It is not a");
L.push("question - it just shows how much of the tree is arriving at once.");
L.push("");
L.push("## 1. The shape at a glance");
L.push("");
for (const root of roots) {
  const kids = childrenOf(root);
  L.push(`- **${root}**${isNew(root) ? " *(new root)*" : ""} - ${kids.length} entries: ${kids.map((k) => k + (childrenOf(k).length ? ` (+${childrenOf(k).length})` : "")).join(", ")}`);
}
L.push("");
L.push("## 2. Every technology and its proposed parent");
L.push("");
L.push("| Technology | Proposed parent | | Came from |");
L.push("|---|---|---|---|");
const sourceOf = (name) => {
  const record = proposal.technologies.find((t) => t.name === name);
  if (!record) return "invented here";
  return record.sources.join(", ");
};
for (const root of roots) {
  const walk = (parent, depth) => {
    for (const child of childrenOf(parent)) {
      L.push(`| ${"&nbsp;".repeat(depth * 4)}${child} | ${parent} | ${isNew(child) ? "**NEW**" : ""} | ${sourceOf(child)} |`);
      walk(child, depth + 1);
    }
  };
  L.push(`| **${root}** | *(root)* | ${isNew(root) ? "**NEW**" : ""} | ${sourceOf(root)} |`);
  walk(root, 1);
}
L.push("");
L.push("## 3. Counts");
L.push("");
L.push(`- ${Object.keys(TREE).length} entries in the tree, ${roots.length} of them roots`);
L.push(`- ${Object.keys(TREE).filter((n) => isNew(n)).length} of those do not exist today`);
L.push(`- ${merged.size} strings merge into an existing record (section 5)`);
L.push(`- ${prose.size} strings stay as prose on their job (section 6)`);
L.push(`- ${Object.keys(RETIRED).length} heading deleted (section 7)`);
if (unfiled.length) {
  L.push("");
  L.push("**UNFILED - these have no home and need one:**");
  for (const name of unfiled) L.push(`- ${name} (from ${sourceOf(name)})`);
}
if (invented.length) {
  L.push("");
  L.push(`*Groups and roots invented for this draft (not in the data): ${invented.join(", ")}.*`);
}
L.push("");
L.push("## 4. The questions (the rest are settled)");
L.push("");
L.push("1. **Are the five new roots the right five, and named the way an employer");
L.push("   should read them?** (CMS & e-commerce, Infrastructure & hosting, Ways of");
L.push("   working, Marketing & analytics, Client & support, Databases, APIs.)");
L.push("   This naming is what a");
L.push("   recruiter actually sees on the resume.");
L.push("2. **Do the four new groups inside Frontend earn their nesting** (SPA");
L.push("   frameworks, Styling, Animation, Build tools), or should Frontend stay flat?");
L.push("3. **`Chrome Extension` has moved out of prose into Desktop & platform** -");
L.push("   veto that if it should stay a memory.");
L.push("");
L.push("## 5. Merges: the same thing typed twice");
L.push("");
L.push("Each becomes an alias (R8), so the original string still finds the record.");
L.push("");
L.push("| Typed somewhere | Becomes |");
L.push("|---|---|");
for (const [from, to] of Object.entries(MERGES)) L.push(`| \`${from}\` | ${to.join(" **and** ")} |`);
L.push("");
L.push("## 6. Prose: not technologies (D12)");
L.push("");
L.push("From `tech` and `code` memories. They describe work, so they stay on their");
L.push("job as prose rather than entering the tree.");
L.push("");
for (const name of PROSE) L.push(`- \`${name}\``);
L.push("");
L.push("## 7. For later, not for this migration");
L.push("");
L.push("**AI is an empty root.** Nothing in the existing content mentions AI, so the");
L.push("heading exists but has no records yet. Harma enters them (the tools, the");
L.push("models, the practices). Until then it stays unticked so the resume does not");
L.push("show an empty heading.");
L.push("");
L.push("APIs holds the frameworks now (REST APIs, OAuth, .NET Web API, Spring Boot).");
L.push("Harma intends to add the remaining API");
L.push("frameworks - Express, C# Web API, Java Spring Boot - once the tree is in.");
L.push("Two consequences to remember then:");
L.push("");
L.push("- One home per skill (D7), so moving Spring Boot to APIs **removes** it from");
L.push("  Backend. These are moves, not copies.");
L.push("- `.NET Web API` is on the merge list below, folding into `.NET`. If a");
L.push("  \"C# Web API\" entry is wanted under APIs, undo that merge - cheap now,");
L.push("  awkward once the records exist.");
L.push("- Express appears nowhere in the data, so it is a genuinely new entry.");
L.push("");
L.push("## 8. Headings deleted");
L.push("");
L.push("These exist today as groupings. Their children are refiled above and the");
L.push("heading itself goes; no skill is lost, because nothing claims a heading.");
L.push("");
for (const [name, why] of Object.entries(RETIRED)) L.push(`- **${name}** - ${why}`);
L.push("");

writeFileSync("docs/skills-tree-draft.md", L.join("\n"), "utf8");
console.log(`[tree-draft] ${Object.keys(TREE).length} entries, ${roots.length} roots, ${unfiled.length} unfiled, ${invented.length} invented.`);
if (unfiled.length) console.log(`[tree-draft] UNFILED: ${unfiled.join(", ")}`);
